-- Trip Checklist: waiver signing + document uploads (private storage).
--
-- These tables are the source of truth for the Trip Checklist. They are
-- RLS-locked with NO policies: only the Node API (service role) reads/writes
-- them. The browser never touches them directly. Document files live in a
-- PRIVATE storage bucket; admins view them via short-lived signed URLs minted
-- server-side. (Legacy user_verifications / licenses bucket are left intact.)

CREATE TABLE IF NOT EXISTS public.booking_waivers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  booking_id uuid NOT NULL REFERENCES public.bookings(id) ON DELETE CASCADE,
  typed_name text NOT NULL,
  agreed_terms boolean NOT NULL,
  agreed_safety boolean NOT NULL,
  signed_at timestamptz DEFAULT now(),
  ip_address text
);

CREATE INDEX IF NOT EXISTS idx_booking_waivers_booking_id ON public.booking_waivers (booking_id);

CREATE TABLE IF NOT EXISTS public.booking_documents (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  booking_id uuid NOT NULL REFERENCES public.bookings(id) ON DELETE CASCADE,
  document_type text NOT NULL,
  storage_path text NOT NULL,
  status text DEFAULT 'uploaded',
  rejection_note text,
  uploaded_at timestamptz DEFAULT now(),
  approved_at timestamptz
);

CREATE INDEX IF NOT EXISTS idx_booking_documents_booking_id ON public.booking_documents (booking_id);

DO $$ BEGIN
