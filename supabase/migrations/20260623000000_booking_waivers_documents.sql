    ADD CONSTRAINT booking_documents_document_type_check
    CHECK (document_type IN ('buoy_insurance_proof', 'government_id', 'boater_safety_card'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  ALTER TABLE public.booking_documents
    ADD CONSTRAINT booking_documents_status_check
    CHECK (status IN ('uploaded', 'approved', 'rejected'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

ALTER TABLE public.booking_waivers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.booking_documents ENABLE ROW LEVEL SECURITY;
